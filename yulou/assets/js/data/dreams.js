export function matchDreams(text) {
  const hits = [];
  for (const d of DREAMS) {
    let score = 0;
    const matched = [];
    for (const k of d.keywords) {
      if (text.includes(k)) {
        score += k.length >= 2 ? 2 : 1;
        matched.push(k);
      }
    }
    if (score > 0) hits.push({ ...d, score, matched });
  }
  hits.sort((a, b) => b.score - a.score);
  return hits.slice(0, 3);
}
