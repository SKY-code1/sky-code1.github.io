function detectTopic(text) {
  let best = null;
  let bestScore = 0;
  for (const t of TOPICS) {
    let score = 0;
    for (const k of t.keywords) if (text.includes(k)) score += k.length;
    if (score > bestScore) {
      best = t;
      bestScore = score;
    }
  }
  return best;
}

export function fengshuiAdvice(text, chart) {
  const topic = detectTopic(text);
  const fav = chart?.elements?.favorable || ["木", "水"];
  const colors = fav.map((e) => ELEMENT_META[e].color.split("、")[0]);
  const dirs = fav.map((e) => ELEMENT_META[e].dir.split("、")[0]);

  if (!topic) {
    return {
      type: "fengshui",
      topic: null,
      intro: "风水这事，老夫更愿意把它拆成三看：看光、看风、看动线。",
      tips: [
        "看光：白天不开灯，屋里能不能看清书上的字？不能就先解决采光。",
        "看风：窗户开五分钟，闷不闷、有没有异味？这比摆什么摆件都重要。",
        "看动线：从进门到坐下，要绕几次？绕得越多，住得越累。",
      ],
      elementTip: `你的喜用是${fav.join("、")}，可以多用${colors.join("、")}，方位上偏${dirs.join("、")}。`,
      avoid: ["一上来就买摆件", "把“风水”当成不改生活习惯的借口"],
      basis: ["未指定空间，给出通用三看", `喜用：${fav.join("、")}`],
    };
  }

  return {
    type: "fengshui",
    topic: topic.title,
    intro: topic.intro,
    tips: topic.tips,
    avoid: topic.avoid,
    elementTip: `结合你的喜用${fav.join("、")}：这个空间可以多用${colors.join("、")}，位置偏${dirs.join("、")}会更顺你的手感。`,
    basis: [`识别空间：${topic.title}`, `关键词：${topic.keywords.filter((k) => text.includes(k)).join("、") || "通用"}`, "民俗说法 + 环境心理，不承诺改运"],
  };
}

